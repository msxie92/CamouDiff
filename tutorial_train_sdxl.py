class StyleAdapter(nn.Module):
    """IP-Adapter"""

    def __init__(self, unet, adapter_modules, ckpt_path=None):
        super().__init__()
        self.unet = unet
        self.adapter_modules = adapter_modules

        if ckpt_path is not None:
            self.load_from_checkpoint(ckpt_path)

    def forward(self, noisy_latents, timesteps, encoder_hidden_states, unet_added_cond_kwargs):
        # Predict the noise residual
        noise_pred = self.unet(
            noisy_latents, timesteps, encoder_hidden_states,added_cond_kwargs=unet_added_cond_kwargs
            ).sample
        return noise_pred

    def load_from_checkpoint(self, ckpt_path: str):
        # Calculate original checksums
        orig_adapter_sum = torch.sum(torch.stack([torch.sum(p) for p in self.adapter_modules.parameters()]))

        state_dict = torch.load(ckpt_path, map_location="cpu")

        # Load state dict for image_proj_model and adapter_modules
        self.adapter_modules.load_state_dict(state_dict["style_adapter"], strict=True)

        # Calculate new checksums
        new_adapter_sum = torch.sum(torch.stack([torch.sum(p) for p in self.adapter_modules.parameters()]))

        # Verify if the weights have changed
        assert orig_adapter_sum != new_adapter_sum, "Weights of adapter_modules did not change!"

        print(f"Successfully loaded weights from checkpoint {ckpt_path}")


